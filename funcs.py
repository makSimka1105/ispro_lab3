def square(n):
    '''
    Возводит число в квадрат.
    
    Параметры:
        n (int/float): число для возведения в квадрат
    
    Возвращаемое значение:
        int/float: квадрат числа
    
    Пример:
        >>> square(7)
        49
    '''
    return n ** 2

def add_binary(a, b):
    '''
    Складывает два числа и возвращает результат в двоичном формате.
    
    Параметры:
        a (int): первое число
        b (int): второе число
    
    Возвращаемое значение:
        str: двоичное представление суммы
    
    Пример:
        >>> add_binary(10, 5)
        '1111'
    '''
    return bin(a + b)[2:]
